def dobro(valor):
    dobrado = valor * 2
    return dobrado

def metade(valor):
    meio = valor / 2
    return meio

def aumentar(valor, porcentagem):
    aumento = valor + (valor * (porcentagem / 100))
    return aumento

def diminuir(valor, porcentagem):
    reducao = valor - (valor * (porcentagem / 100))
    return reducao